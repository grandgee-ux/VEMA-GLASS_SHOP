-- Glass Mart Supabase setup. Run once in Supabase SQL Editor.
-- Creates profiles and business tables. Auth users are created in Supabase Authentication.
create table if not exists public.profiles (
 id uuid primary key references auth.users(id) on delete cascade,
 full_name text not null default '', phone text,
 role text not null default 'customer' check (role in ('admin','staff','customer')),
 created_at timestamptz not null default now()
);
create table if not exists public.products (
 id bigint generated by default as identity primary key, name text not null, category text not null,
 price numeric(12,2) not null check(price >= 0), stock integer not null default 0 check(stock >= 0),
 created_at timestamptz not null default now()
);
create table if not exists public.orders (
 id bigint generated by default as identity primary key, customer_id uuid not null references public.profiles(id),
 customer_name text not null, phone text not null, notes text, payment_method text not null,
 status text not null default 'Pending' check(status in ('Pending','Completed','Cancelled')),
 total numeric(12,2) not null default 0, created_at timestamptz not null default now()
);
create table if not exists public.order_items (
 id bigint generated by default as identity primary key, order_id bigint not null references public.orders(id) on delete cascade,
 product_id bigint references public.products(id) on delete set null, product_name text not null,
 quantity integer not null check(quantity > 0), unit_price numeric(12,2) not null check(unit_price >= 0)
);
create table if not exists public.sales (
 id bigint generated by default as identity primary key, customer_name text not null,
 sale_type text not null check(sale_type in ('Walk-in','Remote')), payment_method text not null,
 total numeric(12,2) not null default 0, recorded_by uuid references public.profiles(id), created_at timestamptz not null default now()
);
create table if not exists public.sale_items (
 id bigint generated by default as identity primary key, sale_id bigint not null references public.sales(id) on delete cascade,
 product_id bigint references public.products(id) on delete set null, product_name text not null,
 quantity integer not null check(quantity > 0), unit_price numeric(12,2) not null check(unit_price >= 0)
);
create table if not exists public.business_settings (
 id integer primary key default 1 check(id=1), business_name text not null default 'Glass Mart',
 phone text, location text, currency text not null default 'KES', updated_at timestamptz not null default now()
);
insert into public.business_settings(id) values(1) on conflict do nothing;

create or replace function public.handle_new_user() returns trigger language plpgsql security definer set search_path='' as $$
begin insert into public.profiles(id,full_name,role) values(new.id,coalesce(new.raw_user_meta_data->>'full_name',''), 'customer'); return new; end; $$;
drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created after insert on auth.users for each row execute function public.handle_new_user();
create or replace function public.my_role() returns text language sql stable security definer set search_path='' as $$ select role from public.profiles where id=(select auth.uid()); $$;

alter table public.profiles enable row level security;
alter table public.products enable row level security;
alter table public.orders enable row level security;
alter table public.order_items enable row level security;
alter table public.sales enable row level security;
alter table public.sale_items enable row level security;
alter table public.business_settings enable row level security;

-- Remove/recreate named policies safely when rerunning this file.
drop policy if exists profile_read_self_admin on public.profiles;
create policy profile_read_self_admin on public.profiles for select to authenticated using(id=(select auth.uid()) or (select public.my_role())='admin');
drop policy if exists products_read_public on public.products;
create policy products_read_public on public.products for select to anon,authenticated using(true);
drop policy if exists products_admin_write on public.products;
create policy products_admin_write on public.products for all to authenticated using((select public.my_role())='admin') with check((select public.my_role())='admin');
drop policy if exists products_staff_update on public.products;
create policy products_staff_update on public.products for update to authenticated using((select public.my_role()) in ('admin','staff')) with check((select public.my_role()) in ('admin','staff'));
drop policy if exists orders_read_owner_staff on public.orders;
create policy orders_read_owner_staff on public.orders for select to authenticated using(customer_id=(select auth.uid()) or (select public.my_role()) in ('admin','staff'));
drop policy if exists orders_insert_owner on public.orders;
create policy orders_insert_owner on public.orders for insert to authenticated with check(customer_id=(select auth.uid()));
drop policy if exists orders_update_staff on public.orders;
create policy orders_update_staff on public.orders for update to authenticated using((select public.my_role()) in ('admin','staff')) with check((select public.my_role()) in ('admin','staff'));
drop policy if exists order_items_read_related on public.order_items;
create policy order_items_read_related on public.order_items for select to authenticated using(exists(select 1 from public.orders o where o.id=order_id and (o.customer_id=(select auth.uid()) or (select public.my_role()) in ('admin','staff'))));
drop policy if exists order_items_insert_owner on public.order_items;
create policy order_items_insert_owner on public.order_items for insert to authenticated with check(exists(select 1 from public.orders o where o.id=order_id and o.customer_id=(select auth.uid()) and o.status='Pending'));
drop policy if exists sales_read_staff_admin on public.sales;
create policy sales_read_staff_admin on public.sales for select to authenticated using((select public.my_role()) in ('admin','staff'));
drop policy if exists sales_insert_staff_admin on public.sales;
create policy sales_insert_staff_admin on public.sales for insert to authenticated with check(recorded_by=(select auth.uid()) and (select public.my_role()) in ('admin','staff'));
drop policy if exists sale_items_read_staff_admin on public.sale_items;
create policy sale_items_read_staff_admin on public.sale_items for select to authenticated using((select public.my_role()) in ('admin','staff'));
drop policy if exists sale_items_insert_staff_admin on public.sale_items;
create policy sale_items_insert_staff_admin on public.sale_items for insert to authenticated with check((select public.my_role()) in ('admin','staff'));
drop policy if exists settings_read_all on public.business_settings;
create policy settings_read_all on public.business_settings for select to anon,authenticated using(true);
drop policy if exists settings_update_admin on public.business_settings;
create policy settings_update_admin on public.business_settings for update to authenticated using((select public.my_role())='admin') with check((select public.my_role())='admin');

grant select on public.products, public.business_settings to anon;
grant select,insert,update,delete on public.profiles,public.products,public.orders,public.order_items,public.sales,public.sale_items,public.business_settings to authenticated;
grant usage,select on all sequences in schema public to authenticated;
grant execute on function public.my_role() to authenticated;

